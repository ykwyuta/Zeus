//! Generates Zeus's code page tables from ICU mapping files (UCM).
//!
//! ```text
//! cargo run -p zeus-cobol --example icu_codepages -- UCM-DIR OUT-DIR
//! ```
//!
//! For each Japanese EBCDIC code page (930, 939, 1390, 1399) it writes the
//! single-byte part as `ibm-N.sbcs`, and the double-byte part, shared by
//! the code pages of a family, as `ibm-300.dbcs` (930, 939) and
//! `ibm-16684.dbcs` (1390, 1399). A table line is
//!
//! ```text
//! K EEEE UUUU[+UUUU]
//! ```
//!
//! with the ICU precision K (0 round trip, 1 fallback to EBCDIC only,
//! 2 to the substitution character, 3 fallback to Unicode only), the
//! EBCDIC code (hex) and the Unicode code points (hex). It is run by
//! tools/icu-codepages.sh.

use std::fmt::Write as _;
use std::path::Path;

const SOURCES: [(&str, u32, &str); 4] = [
    ("ibm-930_P120-1999.ucm", 930, "ibm-300.dbcs"),
    ("ibm-939_P120-1999.ucm", 939, "ibm-300.dbcs"),
    ("ibm-1390_P110-2003.ucm", 1390, "ibm-16684.dbcs"),
    ("ibm-1399_P110-2003.ucm", 1399, "ibm-16684.dbcs"),
];

/// The mappings of a UCM file: (precision, EBCDIC bytes, code points).
fn parse(text: &str) -> Vec<(u8, Vec<u8>, Vec<u32>)> {
    let mut out = Vec::new();
    let mut in_map = false;
    for line in text.lines() {
        let line = line.trim();
        if line == "CHARMAP" {
            in_map = true;
            continue;
        }
        if line == "END CHARMAP" {
            break;
        }
        if !in_map || !line.starts_with("<U") {
            continue;
        }
        let mut parts = line.split_whitespace();
        let (Some(u), Some(b), Some(k)) = (parts.next(), parts.next(), parts.next()) else {
            continue;
        };
        let cps: Vec<u32> = u
            .split('>')
            .filter_map(|x| x.strip_prefix("<U"))
            .filter_map(|x| u32::from_str_radix(x, 16).ok())
            .collect();
        let bytes: Vec<u8> = b
            .split("\\x")
            .filter(|x| !x.is_empty())
            .filter_map(|x| u8::from_str_radix(x, 16).ok())
            .collect();
        let Some(k) = k.strip_prefix('|').and_then(|k| k.parse().ok()) else {
            continue;
        };
        out.push((k, bytes, cps));
    }
    out
}

fn line(out: &mut String, k: u8, bytes: &[u8], cps: &[u32]) {
    let e: String = bytes.iter().map(|b| format!("{b:02X}")).collect();
    let u: Vec<String> = cps.iter().map(|c| format!("{c:04X}")).collect();
    let _ = writeln!(out, "{k} {e} {}", u.join("+"));
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [src, dst] = args.as_slice() else {
        eprintln!("usage: icu_codepages UCM-DIR OUT-DIR");
        std::process::exit(2);
    };
    let (src, dst) = (Path::new(src), Path::new(dst));
    std::fs::create_dir_all(dst).unwrap();
    for (file, ccsid, dbcs_name) in SOURCES {
        let text = std::fs::read_to_string(src.join(file))
            .unwrap_or_else(|e| panic!("{}: {e}", src.join(file).display()));
        let maps = parse(&text);
        let header = format!(
            "# Generated by tools/icu-codepages.sh from ICU {file}\n\
             # (Unicode License V3, see LICENSE-ICU). K EBCDIC UNICODE\n"
        );
        let mut sbcs = header.clone();
        let mut dbcs = header;
        for (k, bytes, cps) in &maps {
            match bytes.len() {
                1 => line(&mut sbcs, *k, bytes, cps),
                _ => line(&mut dbcs, *k, bytes, cps),
            }
        }
        std::fs::write(dst.join(format!("ibm-{ccsid}.sbcs")), sbcs).unwrap();
        // the code pages of a family share their double-byte part
        let dpath = dst.join(dbcs_name);
        let body = |t: &str| {
            t.lines()
                .filter(|l| !l.starts_with('#'))
                .collect::<Vec<_>>()
                .join("\n")
        };
        match std::fs::read_to_string(&dpath) {
            Ok(old) if body(&old) != body(&dbcs) => {
                panic!("{file}: double-byte part differs from {dbcs_name}")
            }
            Ok(_) => {}
            Err(_) => std::fs::write(&dpath, dbcs).unwrap(),
        }
        println!("{file}: {} mappings", maps.len());
    }
}
