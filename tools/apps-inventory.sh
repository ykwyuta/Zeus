#!/bin/sh
# Compiles every COBOL program of CardDemo, GenApp and Bank of Z with zcobc
# and writes the syntax usage inventory (statements, intrinsic functions,
# data description clauses, EXEC CICS/SQL/DLI commands and options) to
# docs/inventory/apps.md.
#
# usage: tools/apps-inventory.sh
set -eu

out=docs/inventory/apps.md
work=work/inventory
bin=target/release

tools/fetch-carddemo.sh >/dev/null
tools/fetch-genapp.sh >/dev/null
tools/fetch-bankofz.sh >/dev/null
cargo build --release -q -p zeus-cobol -p zeus-bms
rm -rf "$work"
mkdir -p "$work" "$(dirname "$out")"

# symbolic maps of the mapsets
bms() { # app dir...
    app=$1
    shift
    mkdir -p "$work/bms-$app"
    for f in "$@"; do
        $bin/zbms "$f" --copy "$work/bms-$app/$(basename "$f" .bms | tr a-z A-Z).cpy"
    done
}
cd_app=.cache/carddemo/app
bms carddemo "$cd_app"/bms/*.bms "$cd_app"/app-*/bms/*.bms
bms genapp .cache/genapp/base/src/*.bms
bms bankofz .cache/bankofz/src/base/cics/bms/*.bms

inv() { # app copy-dirs... -- sources...
    app=$1
    shift
    args=
    while [ "$1" != "--" ]; do
        args="$args -I $1"
        shift
    done
    shift
    # shellcheck disable=SC2086
    $bin/zcobc inventory $args -I "$work/bms-$app" "$@" | sed "s/^/$app	/" >>"$work/all.tsv"
}
for d in "$cd_app" "$cd_app"/app-*; do
    inv carddemo "$d/cpy" "$cd_app/cpy" "$d/dcl" -- "$d"/cbl/*.cbl $(ls "$d"/cbl/*.CBL 2>/dev/null)
done
g=.cache/genapp/base/src
inv genapp "$g" -- "$g"/*.cbl
b=.cache/bankofz/src/base
inv bankofz "$b/cics/copy" "$b/ims/copy" -- "$b"/cics/cobol/*.cbl "$b"/ims/cobol/*.cbl

total_cd=$(ls "$cd_app"/cbl/*.cbl "$cd_app"/cbl/*.CBL "$cd_app"/app-*/cbl/*.cbl 2>/dev/null | wc -l)
total_ga=$(ls "$g"/*.cbl | wc -l)
total_bz=$(ls "$b"/cics/cobol/*.cbl "$b"/ims/cobol/*.cbl | wc -l)

{
    echo "# Syntax usage inventory of the target applications"
    echo
    echo "Generated by \`tools/apps-inventory.sh\` from CardDemo, GenApp and Bank of Z"
    echo "at the commits pinned in \`tools/fetch-*.sh\`. Counts are programs using the"
    echo "item (occurrences in parentheses)."
    echo
    echo "## Compilation"
    echo
    echo "| Application | Programs | Compiled by zcobc |"
    echo "|---|---|---|"
    for a in carddemo:$total_cd genapp:$total_ga bankofz:$total_bz; do
        app=${a%%:*}
        n=${a##*:}
        bad=$(awk -F'\t' -v a="$app" '$1 == a && $2 == "not compiled"' "$work/all.tsv" | wc -l)
        echo "| $app | $n | $((n - bad)) |"
    done
    echo
    if grep -q "	not compiled	" "$work/all.tsv"; then
        echo "Not compiled:"
        echo
        awk -F'\t' '$2 == "not compiled" { printf "- %s %s: %s\n", $1, $3, $6 }' "$work/all.tsv"
        echo
    fi
    for kind in "statement" "function" "data" "EXEC CICS" "EXEC CICS option" "EXEC SQL" "EXEC DLI" "EXEC DLI option"; do
        echo "## $kind"
        echo
        echo "| Item | CardDemo | GenApp | Bank of Z |"
        echo "|---|---|---|---|"
        awk -F'\t' -v k="$kind" '
            $2 == k {
                key = $3; items[key] = 1
                p[$1, key] += $4; o[$1, key] += $5
            }
            END {
                for (it in items) {
                    printf "| %s |", it
                    split("carddemo genapp bankofz", apps, " ")
                    for (j = 1; j <= 3; j++) {
                        a = apps[j]
                        if ((a, it) in p) printf " %d (%d) |", p[a, it], o[a, it]
                        else printf " |"
                    }
                    printf "\n"
                }
            }' "$work/all.tsv" | sort
        echo
    done
} >"$out"
echo "wrote $out"
