#!/bin/sh
# Sets up Bank of Z (IBM/Bank-of-Z) on Zeus and Db2 Community Edition, and
# runs the 3270 transactions of its CICS path.
#
# usage: tools/bankofz.sh setup          # Db2 tables and rows, ABNDFILE, programs, maps
#        tools/bankofz.sh run SCRIPT...  # zcics scripts
#        tools/bankofz.sh serve [PORT]   # TN3270 server (default 3270)
#        tools/bankofz.sh test           # setup, then tools/bankofz/*.txt and
#                                        # the REST API (tools/bankofz/api.zconn)
#        tools/bankofz.sh api [PORT]     # the REST API (zconn, default 9080)
#
# ZEUS_DB2 names the Db2 server (tools/db2ce.sh start prints it); the data
# sets are in ZEUS_HOME (default work/bankofz). BANKZ_CUSTOMERS (default
# 200) customers are generated by BANKDATA.
set -eu

home=${ZEUS_HOME:-work/bankofz}
b=.cache/bankofz
c=$b/src/base/cics
bin=target/release
zjob="$bin/zjob --home $home --loadlib $home/loadlib"
customers=${BANKZ_CUSTOMERS:-200}
: "${ZEUS_DB2:?set ZEUS_DB2 (tools/db2ce.sh start)}"
export ZEUS_DB2
# the programs' unqualified tables are in schema BANKZ
export ZEUS_DB2_SCHEMA=BANKZ

# The values the installation's Ansible templates fill in.
customize() { # template
    sed -e 's/{{ *db2\.db2_hlq *}}/DSN.V13/g; s/{{ *db2\.ssid *}}/DBD1/g' \
        -e 's/{{ *db2\.dsntep *}}/DSNTEP13/g; s/{{ *db2\.runlib *}}/DSN.V13.RUNLIB.LOAD/g' \
        -e 's/{{ *db2\.sqlid *}}/BANKZ/g; s/{{ *db2\.plan *}}/BANKZPLN/g' \
        -e 's/{{ *app\.app_hlq *}}/BANKZ/g; s/{{ *app\.zos_version *}}/V0R1M0/g' \
        -e "s/PARM('1,10000,1,/PARM('1,$customers,1,/" "$1"
}

submit() { # template
    customize "$b/.setup/jcl/cics/$1.j2" >"$home/cntl/$1.jcl"
    $zjob submit "$home/cntl/$1.jcl"
}

setup() {
    tools/fetch-bankofz.sh >/dev/null
    cargo build --release -q -p zeus-cobol -p zeus-bms -p zeus-jcl -p zeus-cics -p zeus-zconnect
    rm -rf "$home"
    mkdir -p "$home/cntl" "$home/loadlib" "$home/maps" "$home/copy"
    for lib in DSN.V13.SDSNLOAD DSN.V13.RUNLIB.LOAD BANKZ.V0R1M0.LOAD; do
        $zjob catalog define-pds $lib --recfm U --lrecl 0
    done
    # mapsets and programs
    for f in $c/bms/*.bms; do
        n=$(basename "$f" .bms)
        $bin/zbms "$f" --copy "$home/copy/$n.cpy" --map "$home/maps/$n.json"
    done
    for f in $c/cobol/*.cbl; do
        n=$(basename "$f" .cbl)
        # CICS programs (not the batch BANKDATA) through the translator
        cics=
        grep -q "EXEC CICS" "$f" && cics=--cics
        $bin/zcobc compile $cics -I $c/copy -I "$home/copy" -o "$home/loadlib/$n.zo" "$f"
    done
    $zjob submit tools/bankofz/abndfile.jcl
    # the Db2 database and tables (Db2-drop first, so that setup can run
    # again), then the generated customers and accounts (BANKDATA)
    submit Db2-drop >/dev/null || true
    submit Db2-create
    submit Db2-insert
}

zcics() {
    $bin/zcics --home "$home" --csd tools/bankofz/BANKZ.CSD --loadlib "$home/loadlib" \
        --mapsets "$home/maps" "$@"
}

zconn() {
    $bin/zconn --api $b/src/api --home "$home" --csd tools/bankofz/BANKZ.CSD \
        --loadlib "$home/loadlib" "$@"
}

case ${1:-} in
    setup) setup ;;
    run)
        shift
        for s in "$@"; do zcics "$s"; done
        ;;
    serve) zcics --serve "${2:-3270}" ;;
    api) zconn serve "${2:-9080}" ;;
    test)
        setup >"$home.setup.log" 2>&1 || { cat "$home.setup.log"; exit 1; }
        for s in tools/bankofz/*.txt; do
            echo "=== $s"
            zcics "$s" >"$home/$(basename "$s" .txt).log" ||
                { cat "$home/$(basename "$s" .txt).log"; exit 1; }
        done
        echo "=== tools/bankofz/api.zconn"
        zconn script tools/bankofz/api.zconn >"$home/api.log" 2>&1 ||
            { cat "$home/api.log"; exit 1; }
        echo "all Bank of Z scripts passed"
        ;;
    *) echo "usage: $0 setup | run SCRIPT... | serve [PORT] | api [PORT] | test" >&2; exit 2 ;;
esac
