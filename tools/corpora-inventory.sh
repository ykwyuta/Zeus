#!/bin/sh
# Compiles every COBOL program of the additional corpora (docs/proposal/0022)
# with zcobc and writes the compilation results and the syntax usage
# inventory to docs/inventory/corpora.md.
#
# usage: tools/corpora-inventory.sh
set -eu

out=docs/inventory/corpora.md
work=work/corpora
bin=target/release
corpora="zfam zecs zuid taxe-fonciere mortgage zopeneditor cobol-course cobol-check acif"

cargo build --release -q -p zeus-cobol -p zeus-bms
rm -rf "$work"
mkdir -p "$work" "$(dirname "$out")"
tools/corpora-programs.sh >"$work/programs.tsv"
awk -F'\t' '$1 == "X" { print $2 "\t" $3 "\t" $4 }' "$work/programs.tsv" >"$work/excluded.tsv"
: >"$work/counts.tsv"
: >"$work/all.tsv"
for corpus in $corpora; do
    # the options (the same for the corpus), then the sources; NUL-separated
    awk -F'\t' -v c="$corpus" '
        $1 == "P" && $2 == c {
            if (!n++) for (i = 4; i <= NF; i++) printf "%s%c", $i, 0
            src[n] = $3
        }
        END { for (i = 1; i <= n; i++) printf "%s%c", src[i], 0 }' "$work/programs.tsv" >"$work/args"
    count=$(awk -F'\t' -v c="$corpus" '$1 == "P" && $2 == c' "$work/programs.tsv" | wc -l)
    printf '%s\t%s\n' "$corpus" "$count" >>"$work/counts.tsv"
    xargs -0 "$bin/zcobc" inventory <"$work/args" | sed "s/^/$corpus	/" >>"$work/all.tsv"
done

{
    echo "# Syntax usage inventory of the additional corpora"
    echo
    echo "Generated by \`tools/corpora-inventory.sh\` from the corpora of"
    echo "[proposal 0022](../proposal/0022-additional-cobol-corpora.md) at the commits"
    echo "pinned in \`tools/fetch-corpora.sh\`. Counts are programs using the item"
    echo "(occurrences in parentheses)."
    echo
    echo "## Compilation"
    echo
    echo "| Corpus | Programs | Compiled by zcobc | Excluded |"
    echo "|---|---|---|---|"
    for corpus in $corpora; do
        n=$(awk -F'\t' -v a="$corpus" '$1 == a { print $2 }' "$work/counts.tsv")
        bad=$(awk -F'\t' -v a="$corpus" '$1 == a && $2 == "not compiled"' "$work/all.tsv" | wc -l)
        ex=$(awk -F'\t' -v a="$corpus" '$1 == a' "$work/excluded.tsv" | wc -l)
        echo "| $corpus | $n | $((n - bad)) | $ex |"
    done
    echo
    if grep -q "	not compiled	" "$work/all.tsv"; then
        echo "Not compiled:"
        echo
        awk -F'\t' '$2 == "not compiled" { printf "- %s %s: %s\n", $1, $3, $6 }' "$work/all.tsv"
        echo
    fi
    echo "Excluded (reasons outside Zeus):"
    echo
    awk -F'\t' '{ printf "- %s %s: %s\n", $1, $2, $3 }' "$work/excluded.tsv"
    echo
    for kind in "statement" "function" "data" "EXEC CICS" "EXEC CICS option" "EXEC SQL"; do
        echo "## $kind"
        echo
        printf '| Item |'
        for corpus in $corpora; do printf ' %s |' "$corpus"; done
        echo
        printf '|---|'
        for corpus in $corpora; do printf -- '---|'; done
        echo
        awk -F'\t' -v k="$kind" -v list="$corpora" '
            $2 == k {
                key = $3; items[key] = 1
                p[$1, key] += $4; o[$1, key] += $5
            }
            END {
                n = split(list, apps, " ")
                for (it in items) {
                    printf "| %s |", it
                    for (j = 1; j <= n; j++) {
                        a = apps[j]
                        if ((a, it) in p) printf " %d (%d) |", p[a, it], o[a, it]
                        else printf " |"
                    }
                    printf "\n"
                }
            }' "$work/all.tsv" | sort
        echo
    done
} >"$out"
echo "wrote $out"
