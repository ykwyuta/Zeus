* HI112A: signed fixed-point add and subtract (Principles of Operation,
* "Add", "Subtract"): 32-bit forms change bits 32-63 only; halfword
* operands are sign-extended; AGF/SGF sign-extend a word; CC 0 zero,
* 1 negative, 2 positive, 3 overflow (the result keeps the low bits).
