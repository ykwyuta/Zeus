* HI113A: add and subtract logical, with carry and borrow
* (Principles of Operation): CC 0 zero/no carry, 1 nonzero/no carry,
* 2 zero/carry, 3 nonzero/carry; for subtract a carry means no
* borrow. ALC/ALCG add the carry of CC 2 or 3; SLB/SLBG subtract a
* borrow when CC is 0 or 1.
HI113A CSECT
         ZHVSHDR
