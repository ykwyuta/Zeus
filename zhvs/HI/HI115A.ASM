* HI115A: multiply and divide (Principles of Operation). M/ML/MLG put
* the double-length product in an even-odd pair; MH/MHI/MSY keep the
* low 32 bits and MSG/MSGR/MGHI the low 64; D/DL/DLG/DSG put the
* remainder in the even and the quotient in the odd register, the
* remainder with the sign of the dividend. No condition code is set.
