* HI116A: loads (Principles of Operation). LH/LHY/LB sign-extend into
* bits 32-63 and keep bits 0-31; LGB/LGBR/LGFI sign-extend to 64
* bits; LLC/LLH zero-extend into bits 32-63; LLIxx load an immediate
* into one part and zero the rest; LCR/LNR/LPR/LTR/LTGR set CC 0
* zero, 1 negative, 2 positive, 3 overflow.
