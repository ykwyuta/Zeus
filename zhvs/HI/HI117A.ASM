* HI117A: store and insert (Principles of Operation). STMY/LMY move
* bits 32-63, STMG/LMG all 64 bits; STC/STCY/STH/STHY/STY store the
* low byte, halfword or word; STCMH/STCMY store the bytes a mask
* selects from bits 0-31 or 32-63; ICMY inserts under a mask and sets
* CC 0 all zero, 1 leftmost bit one, 2 otherwise; ICY inserts bits
* 56-63; IIxx insert a halfword and keep the rest; LAY adds a signed
* 20-bit displacement; LARL gives the address LA gives.
