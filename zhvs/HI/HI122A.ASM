* HI122A: shifts and rotates (Principles of Operation). SLA/SRA shift
* bits 33-63 and keep the sign (CC 0 zero, 1 negative, 2 positive, 3
* a lost bit differs from the sign); SLAG/SRAG do the same on 64
* bits from R3; SLDL/SRDL shift an even-odd pair as 64 bits; RLL
* rotates bits 32-63 of R3. RISBGN/RISBHG/RISBLG rotate R2 and insert
* the selected bits (a zero flag of 128 clears the rest); RNSBG/
* ROSBG/RXSBG AND/OR/XOR them into R1 and set CC 0 zero, 1 not zero.
