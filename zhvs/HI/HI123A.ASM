* HI123A: branches (Principles of Operation). Each check counts in R3
* the instructions that ran, so a wrong decision gives another
* count. BAL/BALR/BAS/BRAS/BRASL put the address of the next
* instruction in R1 (compared with LA of the return label under the
* 31-bit mask); BC/BCR/BRC/BRCL branch when the CC bit of the mask is
* one; BCTR/BCTG/BCTGR/BRCT/BRCTG/BRCTH count down and branch on
* nonzero (BCTR with R2 0 only counts); EXRL executes a target with
* its length ORed from R1.
