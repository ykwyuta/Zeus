* HI124A: interlocked-access and compare-and-swap (Principles of
* Operation). LAA/LAAL/LAN/LAO/LAX (and the G forms) return the old
* storage value in R1 and store old op R3; CC from the new value
* (signed or logical add, 0/1 for the logical operations). CS*/CDS*:
* on equal store R3 and CC 0, otherwise load the storage into R1 and
* CC 1. TS sets CC from the leftmost bit and stores ones. LPD/LPDG
* load two operands into a pair (CC 0); LPQ/STPQ move a quadword.
HI124A CSECT
         ZHVSHDR
* LAA-OVERFLOW
         XC ACTUAL(16),ACTUAL
         LG 5,=XL8'000000007FFFFFFF'
         ST 5,W1
         LG 4,=XL8'0000000000000001'
