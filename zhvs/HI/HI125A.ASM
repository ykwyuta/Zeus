* HI125A: conversions, long moves and other instructions (Principles
* of Operation). CVBY/CVBG convert 8 and 16 packed bytes to binary,
* CVDY/CVDG the reverse (sign C or D); MVCLE/CLCLE are repeated while
* CC is 3 and end with CC 0 equal lengths, 1 first shorter or low, 2
* first longer or high; TRTR scans from the right and returns the
* address and function byte; LAM/STAM move access registers; SPM sets
* the CC from bits 34-35; BSM with R2 0 records the addressing mode
* in bit 32; BASSM links with the mode bit; SAM64 lets LA form a
* 64-bit address.
HI125A CSECT
         ZHVSHDR
* CVBY
         XC ACTUAL(16),ACTUAL
         LG 3,=XL8'1122334455667788'
         CVBY 3,P8
         STG 3,ACTUAL
         ZHVSCHK CVBY,ACTUAL,ZE000,16
* CVBG
