         SQEB 0,E2
         STE 0,ACTUAL
         ZHVSCHK SQEB,ACTUAL,ZE006,16
* TCDB-POS-NORMAL
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LD 0,=XL8'3FF8000000000000'
         TCDB 0,X'200'
         IPM 0
         SRL 0,28
         ST 0,ACTUAL+12
         ZHVSCHK TCDB-POS-NORMAL,ACTUAL,ZE007,16
* TCDB-NOT-ZERO
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LD 0,=XL8'3FF8000000000000'
         TCDB 0,X'800'
         IPM 0
         SRL 0,28
         ST 0,ACTUAL+12
         ZHVSCHK TCDB-NOT-ZERO,ACTUAL,ZE008,16
* TCEB-NEG-NORMAL
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LE 0,=X'C0000000'
         TCEB 0,X'100'
         IPM 0
         SRL 0,28
         ST 0,ACTUAL+12
         ZHVSCHK TCEB-NEG-NORMAL,ACTUAL,ZE009,16
* TCXB-POS-ZERO
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LD 0,=XL8'0000000000000000'
         LD 2,=XL8'00'
         TCXB 0,X'800'
         IPM 0
         SRL 0,28
         ST 0,ACTUAL+12
         ZHVSCHK TCXB-POS-ZERO,ACTUAL,ZE010,16
* LFPC-EFPC
         XC ACTUAL(16),ACTUAL
         LFPC W2
         EFPC 3
         LFPC ZW
         ST 3,ACTUAL
         ZHVSCHK LFPC-EFPC,ACTUAL,ZE011,16
* SRNM
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         SRNM 1
         EFPC 3
         SRNM 0
         ST 3,ACTUAL
         ZHVSCHK SRNM,ACTUAL,ZE012,16
* SRNMB
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         SRNMB 3
         EFPC 3
         SRNMB 0
         ST 3,ACTUAL
         ZHVSCHK SRNMB,ACTUAL,ZE013,16
* SRNMT
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         SRNMT 1
         EFPC 3
         SRNMT 0
         ST 3,ACTUAL
         ZHVSCHK SRNMT,ACTUAL,ZE014,16
