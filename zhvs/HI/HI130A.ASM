* HI130A: binary floating point lengthening, square root, test data
* class and the floating-point control register (Principles of
* Operation). LDEB/LXDB/LXEB lengthen exactly; MDEB/MXDB multiply
* into the longer format; TCxB sets CC 1 when the class bit of the
* mask is one (X200 +normal, X100 -normal, X800 +zero, X020 +inf);
* SRNM/SRNMB set the BFP rounding mode in FPC bits 29-31 (SRNM bits
* 30-31), SRNMT the DFP mode in bits 25-27; LFPC/EFPC load and
* extract the FPC.
HI130A CSECT
         ZHVSHDR
* LDEB-EXACT
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LDEB 0,E01
         STD 0,ACTUAL
         ZHVSCHK LDEB-EXACT,ACTUAL,ZE000,16
* LXDB
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LXDB 0,D15
         STD 0,ACTUAL
         STD 2,ACTUAL+8
         ZHVSCHK LXDB,ACTUAL,ZE001,16
* LXEB
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LXEB 0,EM025
         STD 0,ACTUAL
         STD 2,ACTUAL+8
         ZHVSCHK LXEB,ACTUAL,ZE002,16
* MDEB-EXACT
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LE 0,=X'3DCCCCCD'
         MDEB 0,E01
         STD 0,ACTUAL
         ZHVSCHK MDEB-EXACT,ACTUAL,ZE003,16
* MXDB
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         LD 0,=XL8'4008000000000000'
         MXDB 0,D05
         STD 0,ACTUAL
         STD 2,ACTUAL+8
         ZHVSCHK MXDB,ACTUAL,ZE004,16
* SQDB
         XC ACTUAL(16),ACTUAL
         LFPC ZW
         SQDB 0,D2
         STD 0,ACTUAL
         ZHVSCHK SQDB,ACTUAL,ZE005,16
* SQEB
         XC ACTUAL(16),ACTUAL
