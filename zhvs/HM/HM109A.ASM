* HM109A: system variable symbols whose form the HLASM Language
* Reference fixes: &SYSCLOCK (26 characters, YYYY-MM-DD
* HH:MM:SS.mmmmmm, T' U), &SYSSEQF (columns 73-80 of the open-code
* macro call), &SYSIN_MEMBER (the source member), &SYSM_SEV and
* &SYSM_HSEV (three digits, the highest MNOTE severity), &SYSSTMT
* (eight digits, the next statement number), &SYSOPT_DBCS and
* &SYSOPT_XOBJECT (T' N, one character; NODBCS by default),
* &SYSOPT_OPTABLE (UNI by default) and T' U of &SYSVER, &SYSASM,
* &SYSTEM_ID, &SYSJOB and &SYSSTEP. Their values depend on the
* system and are not compared.
         MACRO
         ZINNER
         MNOTE 2,'ZINNER SEVERITY 2'
         MEND
         MACRO
         ZSYS
         GBLC  &GCLK,&GSEQ,&GSEV,&GHSEV,&GMEM,&GCLKT
&GCLK    SETC  '&SYSCLOCK'
&GCLKT   SETC  T'&SYSCLOCK
&GSEQ    SETC  '&SYSSEQF'
&GMEM    SETC  '&SYSIN_MEMBER'
         ZINNER
&GSEV    SETC  '&SYSM_SEV'
&GHSEV   SETC  '&SYSM_HSEV'
         MEND
